"""Capture original public screenshots from a fresh synthetic app session."""
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
from uuid import uuid4
from tools.build_native import ROOT, add_sdk_arguments, resolve_sdks, build_environment
from tools.fixtures import write_plotter


def write_plotter_visualization(assets):
    from PIL import Image, ImageDraw

    width, height = 960, 560
    frames = []
    for phase in (0, 3, 6, 3):
        image = Image.new("RGB", (width, height), "#12121a")
        draw = ImageDraw.Draw(image)
        draw.rectangle((38, 38, width - 38, height - 38), outline="#343449", width=2)
        draw.text((70, 70), "SYNTHETIC PLOTTER ASSEMBLY", fill="#b9a7d6")
        draw.text((70, 94), "desktop 3-axis / local demo visualization", fill="#8990a7")

        bed = [(170, 390), (630, 390), (780, 315), (320, 315)]
        draw.polygon(bed, fill="#566176", outline="#93a0ba")
        draw.line((320, 315, 320, 360), fill="#a5b1ca", width=3)
        draw.line((780, 315, 780, 360), fill="#a5b1ca", width=3)

        for x in (185, 690):
            draw.polygon([(x, 350), (x + 24, 338), (x + 24, 150), (x, 162)], fill="#8791a6")
        draw.polygon([(185, 150), (690, 150), (714, 138), (209, 138)], fill="#a99bc7")
        draw.line((225, 175, 650, 175), fill="#d0b1df", width=12)

        carriage_x = 405 + phase
        draw.polygon(
            [(carriage_x, 160), (carriage_x + 92, 160), (carriage_x + 108, 182),
             (carriage_x + 16, 182)],
            fill="#d29d68",
        )
        draw.rectangle((carriage_x + 38, 178, carriage_x + 66, 270), fill="#74bcc1")
        draw.ellipse((carriage_x + 31, 255, carriage_x + 73, 297), fill="#e1b467")
        draw.line((carriage_x + 52, 295, carriage_x + 52, 352), fill="#e1b467", width=7)
        draw.ellipse((carriage_x + 46, 345, carriage_x + 58, 357), fill="#f2d6a0")

        draw.ellipse((690, 270, 760, 340), fill="#bd82c3", outline="#e3b8e4", width=3)
        draw.ellipse((710, 286, 740, 316), fill="#12121a")
        draw.text((70, 470), "X rail     Z carriage     pen holder     work surface", fill="#c6cad8")
        frames.append(image)

    assets.mkdir(parents=True, exist_ok=True)
    frames[0].save(assets / "workspace-demo.gif", save_all=True, append_images=frames[1:],
                   duration=900, loop=0, optimize=True)
    frames[0].save(assets / "workspace-plotter.png", optimize=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    add_sdk_arguments(parser)
    args = parser.parse_args()
    resolve_sdks(args)
    output = ROOT / "artifacts" / ("public-demo-" + uuid4().hex[:8])
    fixture = write_plotter(output / "input")
    assets = ROOT / "site/assets"
    assets.mkdir(parents=True, exist_ok=True)
    write_plotter_visualization(assets)
    hashes = []
    for theme in ("dark", "light"):
        env = build_environment(args.qt_prefix, args.occt_prefix, args.toolchain_env)
        env = {name: value for name, value in env.items() if not name.startswith(("OPENAI_", "CODEX_", "ANTHROPIC_", "PROMPTCAD_"))}
        env["CAD_UI_THEME"] = theme
        subprocess.run([str(args.build_dir / "bin/PromptToCAD.exe"), "--workspace", str(ROOT),
            "--open", str(fixture), "--demo-capture", str(output / theme), "--smoke-size", "1600x1000"],
            cwd=ROOT, env=env, check=True, timeout=150)
        # Re-encode pixels only: strips metadata and never samples existing user images.
        from PIL import Image
        target = assets / f"workspace-{theme}.png"
        with Image.open(output / theme / target.name) as image:
            image.convert("RGB").save(target, optimize=True)
        hashes.append(f"- `{target.name}` SHA-256: `{hashlib.sha256(target.read_bytes()).hexdigest()}`")
    hashes.append(f"- `workspace-demo.gif` SHA-256: `{hashlib.sha256((assets / 'workspace-demo.gif').read_bytes()).hexdigest()}`")
    hashes.append(f"- `workspace-plotter.png` SHA-256: `{hashlib.sha256((assets / 'workspace-plotter.png').read_bytes()).hexdigest()}`")
    (assets / "PROVENANCE.md").write_text("# Public demo media\n\nThe plotter visualization is original local artwork generated by `python -m tools.create_demo` from the same synthetic component list as `tools.fixtures.plotter_definition()`. It is not a screenshot, screen recording, or live AI result. The native capture path remains available for a machine with a working graphical session. Every attempted capture uses a fresh isolated project, identity and settings directory; no personal project, chat, account, image, or CAD file is opened.\n\nPrompt: Create a desktop 3-axis pen plotter with a work surface, frame, X rail, carriage, Z axis and pen holder. Keep the major assemblies as separate components.\n\nResult: eight independently rendered CAD solids from the local backend, represented in the README by an animated visualization with a static PNG fallback.\n\n" + "\n".join(hashes) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
